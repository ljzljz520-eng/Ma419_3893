func ArchiveNotes() []ArchiveNote { return append([]ArchiveNote(nil), archiveNotes...) }
func ArchiveByCategory(category string) []ArchiveNote {
	out := []ArchiveNote{}
	for _, n := range archiveNotes {
		if n.Category == category {
			out = append(out, n)
		}
	}
	return out
}
func ArchiveSummary() map[string]int {
	out := map[string]int{}
	for _, n := range archiveNotes {
		out[n.Category]++
	}
	return out
}
